// Service worker de Molinari Control Operativo.
// Estrategia: cache-first con actualización en segundo plano ("stale-while-revalidate").
// Esto permite que la app abra instantáneamente y funcione sin conexión después de la
// primera visita, mientras se actualiza sola en segundo plano cuando hay internet.
//
// Si en el futuro se publica una nueva versión del index.html, subir el número de
// CACHE_NAME (v1 -> v2, etc.) para que los dispositivos descarten la copia vieja.
const CACHE_NAME = "molinari-v1";
const APP_SHELL = [
  "./",
  "./index.html",
  "./manifest.json",
  "./icon-192.png",
  "./icon-512.png",
  "./icon-512-maskable.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((response) => {
          if (response && response.status === 200) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
